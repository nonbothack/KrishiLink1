import { apiCall } from '../lib/http';
export { apiCall };
export const isExplicitDemoMode = () => false;
const query = (params = {}) => new URLSearchParams(Object.entries(params).filter(([,v]) => v !== null && v !== undefined && v !== '' && v !== 'All')).toString();
async function list(path, params) {
  const res = await apiCall(`/api/v1/${path}?${query(params)}`);
  if (!res.success) return { ...res, data: [] };
  return { ...res, data: Array.isArray(res.data) ? res.data : res.data?.items || [], total: res.data?.total, pages: res.data?.pages, provenance: 'api' };
}
const post = (path, data, key) => apiCall(`/api/v1/${path}`, { method: 'POST', body: data ? JSON.stringify(data) : undefined, ...(key ? { headers: { 'Idempotency-Key': key } } : {}) });
