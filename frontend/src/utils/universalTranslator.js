// Translate any arbitrary string into the target language
export function translateString(str, lang = 'en') {
  if (!str || typeof str !== 'string') return str;
  if (!lang || lang === 'en') return str;

  const trimmed = str.trim();
  const dict = UNIVERSAL_DICTIONARY[lang];
  if (!dict) return str;

  // Direct exact match
  if (dict[trimmed]) {
    // Preserve leading/trailing whitespace
    const leading = str.match(/^\s*/)[0];
    const trailing = str.match(/\s*$/)[0];
    return leading + dict[trimmed] + trailing;
  }

  // Check if string contains known crop or market
  let result = str;
  for (const [enTerm, localizedTerm] of Object.entries(dict)) {
    if (enTerm.length > 2 && result.includes(enTerm)) {
      result = result.split(enTerm).join(localizedTerm);
    }
  }

  return result;
}

// Global WeakMap to retain original text content of DOM nodes
const nodeOriginalText = new WeakMap();

// Auto-translate DOM text nodes and attributes safely without breaking React Fiber
export function translateDOMTree(root = document.body, lang = 'en') {
  if (!root || typeof window === 'undefined') return;

  const dict = UNIVERSAL_DICTIONARY[lang];
  const isEn = !lang || lang === 'en';

  const walker = document.createTreeWalker(
    root,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        // Skip script, style, code, pre
        const parentTag = node.parentElement?.tagName?.toLowerCase();
        if (['script', 'style', 'code', 'pre', 'noscript'].includes(parentTag)) {
          return NodeFilter.FILTER_REJECT;
        }
        if (!node.nodeValue || !node.nodeValue.trim()) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    }
  );

  const textNodes = [];
  while (walker.nextNode()) {
    textNodes.push(walker.currentNode);
  }

  for (const node of textNodes) {
    const currentVal = node.nodeValue;
    if (!nodeOriginalText.has(node)) {
      nodeOriginalText.set(node, currentVal);
    }

    const originalVal = nodeOriginalText.get(node);

    if (isEn) {
      if (node.nodeValue !== originalVal) {
        node.nodeValue = originalVal;
      }
    } else if (dict) {
      const trimmed = originalVal.trim();
      let translated = dict[trimmed];

      if (!translated) {
        // Multi-word partial replacement for known agricultural terms
        let candidate = originalVal;
        let matched = false;
        for (const [key, val] of Object.entries(dict)) {
          if (key.length > 2 && candidate.includes(key)) {
            candidate = candidate.split(key).join(val);
            matched = true;
          }
        }
        if (matched) translated = candidate;
      }

      if (translated) {
        const leading = originalVal.match(/^\s*/)[0];
        const trailing = originalVal.match(/\s*$/)[0];
        const finalVal = leading + (dict[trimmed] || translated) + trailing;
        if (node.nodeValue !== finalVal) {
          node.nodeValue = finalVal;
        }
      }
    }
  }

  // Also translate input placeholders and title attributes
  const inputs = root.querySelectorAll('input[placeholder], textarea[placeholder]');
  inputs.forEach(input => {
    if (!nodeOriginalText.has(input)) {
      nodeOriginalText.set(input, input.getAttribute('placeholder'));
    }
    const orig = nodeOriginalText.get(input);
    if (isEn) {
      input.setAttribute('placeholder', orig);
    } else {
      input.setAttribute('placeholder', translateString(orig, lang));
    }
  });
}
